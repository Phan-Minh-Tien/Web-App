CREATE DATABASE IF NOT EXISTS hoanggia CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE hoanggia;

CREATE TABLE IF NOT EXISTS users (
  id INT AUTO_INCREMENT PRIMARY KEY,
  username VARCHAR(100) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  role VARCHAR(50) DEFAULT 'user',
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS po_input (
  id INT AUTO_INCREMENT PRIMARY KEY,
  so_po VARCHAR(100),
  khach_hang VARCHAR(255),
  ngay_giao VARCHAR(50),
  items_json JSON,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS nvl_master (
  id INT AUTO_INCREMENT PRIMARY KEY,
  ma_hang VARCHAR(100),
  ten_vat_tu VARCHAR(255),
  nha_cung_cap VARCHAR(255),
  dvt VARCHAR(50),
  don_gia DECIMAL(18,2) DEFAULT 0,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS lsx (
  id INT AUTO_INCREMENT PRIMARY KEY,
  ma VARCHAR(100),
  ma_hang VARCHAR(100),
  ten_sp VARCHAR(255),
  so_po VARCHAR(100),
  khach VARCHAR(255),
  sl_yeu_cau DECIMAL(18,2) DEFAULT 0,
  payload_json JSON,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS machines (
  id INT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(255) NOT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS customers (
  id INT AUTO_INCREMENT PRIMARY KEY,
  ten VARCHAR(255),
  viet_tat VARCHAR(100),
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

